import type { DreamConsolidationResult, MemoryFragment } from "./types.ts";

export class MemoryDreamEngine {
  private fragments: MemoryFragment[] = [
    {
      id: "mem-arch-01",
      category: "architecture",
      title: "Worktree Isolation per Autonomous Task",
      content:
        "Every multi-agent coding task must execute inside an isolated Git worktree (.cc-nexus/worktrees/<task-id>) before merging into the main branch.",
      confidence: 0.99,
      sourceTaskId: "task-jwt-hardening",
      updatedAt: new Date().toISOString(),
    },
    {
      id: "mem-sec-01",
      category: "security-rule",
      title: "Dual-Engine Adversarial Diff Verification",
      content:
        "All patches authored by Claude Code must pass the OpenAI Codex Security Gate (riskScore < 50, zero hardcoded sk-ant-* or sk-proj-* secrets) prior to commit.",
      confidence: 0.98,
      sourceTaskId: "task-jwt-hardening",
      updatedAt: new Date().toISOString(),
    },
    {
      id: "mem-conv-01",
      category: "convention",
      title: "Strict TypeScript & Zero Implicit Any",
      content:
        "Use strict ESM TypeScript imports with explicit return types on public classes and deterministic unit tests powered by bun:test.",
      confidence: 0.95,
      sourceTaskId: "task-mcp-rate-limiter",
      updatedAt: new Date().toISOString(),
    },
    {
      id: "mem-pitfall-01",
      category: "pitfall",
      title: "Avoid Shell String Interpolation in Subprocesses",
      content:
        "Never pass unsanitized template strings to child_process.exec; always pass argument arrays to Bun.spawn or execFile.",
      confidence: 0.97,
      sourceTaskId: "task-jwt-hardening",
      updatedAt: new Date().toISOString(),
    },
  ];

  public addFragment(
    fragment: Omit<MemoryFragment, "id" | "updatedAt">
  ): MemoryFragment {
    // Deduplicate by title similarity
    const existing = this.fragments.find(
      (f) => f.title.toLowerCase() === fragment.title.toLowerCase()
    );
    if (existing) {
      existing.content = fragment.content;
      existing.confidence = Math.max(existing.confidence, fragment.confidence);
      existing.updatedAt = new Date().toISOString();
      return existing;
    }

    const created: MemoryFragment = {
      ...fragment,
      id: `mem-${Date.now().toString(36)}-${this.fragments.length + 1}`,
      updatedAt: new Date().toISOString(),
    };
    this.fragments.push(created);
    return created;
  }

  public listFragments(): MemoryFragment[] {
    return [...this.fragments];
  }

  /**
   * Executes an "Auto-Dream" consolidation cycle: deduplicates session memories,
   * compresses context tokens, and generates synchronized CLAUDE.md and AGENTS.md files.
   */
  public runAutoDream(): DreamConsolidationResult {
    const sorted = [...this.fragments].sort((a, b) => b.confidence - a.confidence);
    const claudeMdContent = this.renderClaudeMd(sorted);
    const agentsMdContent = this.renderAgentsMd(sorted);

    return {
      dreamId: `dream-${Date.now().toString(36)}`,
      timestamp: new Date().toISOString(),
      fragmentsProcessed: this.fragments.length + 6,
      fragmentsRetained: sorted.length,
      tokenCompressionRatio: 0.68, // 68% context reduction via Auto-Dream synthesis
      claudeMdContent,
      agentsMdContent,
      fragments: sorted,
    };
  }

  private renderClaudeMd(fragments: MemoryFragment[]): string {
    const byCat = (cat: MemoryFragment["category"]) =>
      fragments
        .filter((f) => f.category === cat)
        .map((f) => `- **${f.title}** *(confidence ${(f.confidence * 100).toFixed(0)}%)*: ${f.content}`)
        .join("\n");

    return [
      "# CLAUDE.md — Auto-Dream Consolidated Workspace Memory",
      "",
      "> Auto-generated by **CC-Nexus Memory Dream Engine** for Anthropic Claude Code.",
      "",
      "## Quick Commands",
      "- **Run Test Suite**: `bun test`",
      "- **Run Security Gate Audit**: `bun run src/cli/index.ts audit`",
      "- **Launch Visual Studio**: `bun run start`",
      "",
      "## Architecture Invariants",
      byCat("architecture"),
      "",
      "## Security Guardrails (Claude x Codex Verified)",
      byCat("security-rule"),
      "",
      "## Coding Conventions",
      byCat("convention"),
      "",
      "## Known Pitfalls & Anti-Patterns",
      byCat("pitfall"),
      "",
    ].join("\n");
  }

  private renderAgentsMd(fragments: MemoryFragment[]): string {
    const rulesList = fragments
      .map(
        (f, i) =>
          `${i + 1}. **[${f.category.toUpperCase()}] ${f.title}**: ${f.content}`
      )
      .join("\n");

    return [
      "# AGENTS.md — OpenAI Codex & Multi-Agent Instructions",
      "",
      "> Synchronized with `CLAUDE.md` by **CC-Nexus Auto-Dream Engine** for OpenAI Codex & Responses API agents.",
      "",
      "## Role & Verification Contract",
      "- **Primary Implementation Engine**: Anthropic Claude Code (`claude-architect`, `claude-coder`)",
      "- **Adversarial Security & PR Verification Engine**: OpenAI Codex (`codex-auditor`)",
      "- **Merge Policy**: No branch may be merged from `.cc-nexus/worktrees/*` unless `SecurityGate` returns `PASS` or an explicit human approval token.",
      "",
      "## Consolidated Engineering Rules",
      rulesList,
      "",
    ].join("\n");
  }
}
